def cargar():
    for nombre in ("reglas.json", "reglas.ejemplo.json"):
        try:
            with open(os.path.join(AQUI, nombre), encoding="utf-8") as f:
                return json.load(f)
        except (OSError, ValueError):
            continue
    return {}


